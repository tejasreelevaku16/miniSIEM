"""
Mini-SIEM Incident Correlation Engine.

Correlates security alerts generated by disparate detection rules into
high-level, unified security incidents based on:
- Source IP addresses
- Targeted usernames
- Temporal proximity (sliding correlation windows)
- Multi-stage attack progression (e.g. Brute Force followed by Success)
"""

from dataclasses import dataclass, field
from datetime import datetime, timedelta
from pathlib import Path
from typing import Optional

from app.database import DEFAULT_DB_PATH, get_db_connection, init_db
from app.services.detection_engine import Alert


@dataclass
class CorrelatedIncident:
    """Represents a unified security incident composed of correlated alerts."""

    source_ip: str
    failure_count: int
    window_start: datetime
    window_end: datetime
    severity: str
    status: str
    description: str
    targeted_usernames: list[str]
    rule_id: str
    mitre_technique: str
    recommended_action: str
    alerts: list[Alert] = field(default_factory=list)
    id: Optional[int] = None


def _escalate_severity(severities: list[str], has_multi_stage: bool = False) -> str:
    """Calculates overall incident severity with multi-stage attack escalation."""
    if has_multi_stage:
        return "CRITICAL"

    sev_order = {"CRITICAL": 4, "HIGH": 3, "MEDIUM": 2, "LOW": 1}
    highest_score = max((sev_order.get(s.upper(), 1) for s in severities), default=1)

    score_to_name = {4: "CRITICAL", 3: "HIGH", 2: "MEDIUM", 1: "LOW"}
    return score_to_name[highest_score]


def correlate_alerts(
    alerts: list[Alert],
    correlation_window_minutes: int = 30,
) -> list[CorrelatedIncident]:
    """
    Groups and merges related security alerts into unified incidents.

    Deduplication and Correlation Rules:
    1. Alerts from the same source IP occurring within `correlation_window_minutes`
       are merged into one incident.
    2. If an IP triggers both AUTH-001 (Brute-Force) and AUTH-002 (Success after failure),
       the incident escalates to CRITICAL (multi-stage attack progression).
    3. Multi-rule MITRE techniques are compiled.
    """
    if not alerts:
        return []

    # 1. Group alerts by source IP
    alerts_by_ip: dict[str, list[Alert]] = {}
    for alert in alerts:
        alerts_by_ip.setdefault(alert.source_ip, []).append(alert)

    window_delta = timedelta(minutes=correlation_window_minutes)
    incidents: list[CorrelatedIncident] = []

    for source_ip, ip_alerts in alerts_by_ip.items():
        # Sort chronologically by start time
        ip_alerts.sort(key=lambda a: a.window_start)

        clusters: list[list[Alert]] = []
        current_cluster: list[Alert] = [ip_alerts[0]]

        for alert in ip_alerts[1:]:
            last_in_cluster = current_cluster[-1]
            if alert.window_start - last_in_cluster.window_end <= window_delta:
                current_cluster.append(alert)
            else:
                clusters.append(current_cluster)
                current_cluster = [alert]

        if current_cluster:
            clusters.append(current_cluster)

        # Build CorrelatedIncident for each cluster
        for cluster in clusters:
            start_time = min(a.window_start for a in cluster)
            end_time = max(a.window_end for a in cluster)
            total_events = sum(a.failure_count for a in cluster)

            # Collect unique targeted usernames
            users = sorted(set(
                user
                for a in cluster
                for user in a.targeted_usernames
                if user
            ))

            # Detect multi-stage progression
            rule_ids = set(a.rule_id for a in cluster)
            has_multi_stage = ("AUTH-001" in rule_ids and "AUTH-002" in rule_ids)

            severities = [a.severity for a in cluster]
            incident_severity = _escalate_severity(severities, has_multi_stage=has_multi_stage)

            # Determine primary rule and MITRE mapping
            primary_rule = "/".join(sorted(rule_ids))
            mitre_techs = sorted(set(a.mitre_attack_id for a in cluster if a.mitre_attack_id))
            mitre_str = ", ".join(mitre_techs) if mitre_techs else "T1110"

            if has_multi_stage:
                desc = (
                    f"CRITICAL Multi-Stage Attack from {source_ip}: Brute-force guessing "
                    f"followed by successful credential compromise for user(s) '{', '.join(users)}'. "
                    f"Total {len(cluster)} detection alerts aggregated."
                )
                action = (
                    "URGENT: Immediately isolate host / revoke active session tokens for affected accounts, "
                    "enforce password reset, and block source IP at perimeter firewall."
                )
            elif len(cluster) > 1:
                desc = (
                    f"Correlated incident involving {len(cluster)} alert(s) from {source_ip}. "
                    f"Rules triggered: {primary_rule}. Targeted users: {', '.join(users) or 'none'}."
                )
                action = cluster[0].recommended_action
            else:
                desc = cluster[0].description
                action = cluster[0].recommended_action

            incident = CorrelatedIncident(
                source_ip=source_ip,
                failure_count=total_events,
                window_start=start_time,
                window_end=end_time,
                severity=incident_severity,
                status="Open",
                description=desc,
                targeted_usernames=users,
                rule_id=primary_rule,
                mitre_technique=mitre_str,
                recommended_action=action,
                alerts=cluster,
            )
            incidents.append(incident)

    incidents.sort(key=lambda inc: inc.window_start)
    return incidents


def persist_correlated_incidents(
    incidents: list[CorrelatedIncident],
    db_path: str | Path = DEFAULT_DB_PATH,
) -> tuple[int, int]:
    """
    Saves correlated incidents into SQLite, avoiding duplicate incident entries,
    and links each component alert in the alerts table.

    Returns:
        (saved_incidents, duplicate_incidents)
    """
    if not incidents:
        return 0, 0

    init_db(db_path)
    conn = get_db_connection(db_path)

    saved_count = 0
    duplicate_count = 0

    try:
        with conn:
            cursor = conn.cursor()
            record_time = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

            for inc in incidents:
                start_str = inc.window_start.strftime("%Y-%m-%d %H:%M:%S")
                end_str = inc.window_end.strftime("%Y-%m-%d %H:%M:%S")
                users_str = ", ".join(inc.targeted_usernames)

                cursor.execute("""
                    INSERT OR IGNORE INTO incidents (
                        source_ip,
                        failure_count,
                        window_start,
                        window_end,
                        severity,
                        description,
                        targeted_usernames,
                        created_at,
                        status,
                        rule_id,
                        mitre_technique,
                        recommended_action,
                        updated_at
                    )
                    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?);
                """, (
                    inc.source_ip,
                    inc.failure_count,
                    start_str,
                    end_str,
                    inc.severity,
                    inc.description,
                    users_str,
                    record_time,
                    inc.status,
                    inc.rule_id,
                    inc.mitre_technique,
                    inc.recommended_action,
                    record_time,
                ))

                if cursor.rowcount > 0:
                    saved_count += 1
                    incident_id = cursor.lastrowid
                else:
                    duplicate_count += 1
                    cursor.execute("""
                        SELECT id FROM incidents
                        WHERE source_ip = ? AND window_start = ? AND window_end = ?;
                    """, (inc.source_ip, start_str, end_str))
                    row = cursor.fetchone()
                    incident_id = row[0] if row else None

                inc.id = incident_id

                # Link alerts to this incident
                for alert in inc.alerts:
                    alert_start = alert.window_start.strftime("%Y-%m-%d %H:%M:%S")
                    alert_end = alert.window_end.strftime("%Y-%m-%d %H:%M:%S")
                    user = alert.targeted_usernames[0] if alert.targeted_usernames else None

                    cursor.execute("""
                        INSERT INTO alerts (
                            rule_id,
                            rule_name,
                            source_ip,
                            username,
                            event_count,
                            first_observed,
                            last_observed,
                            severity,
                            description,
                            mitre_technique_id,
                            mitre_technique_name,
                            incident_id,
                            created_at
                        )
                        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?);
                    """, (
                        alert.rule_id,
                        alert.rule_name,
                        alert.source_ip,
                        user,
                        alert.failure_count,
                        alert_start,
                        alert_end,
                        alert.severity,
                        alert.description,
                        alert.mitre_attack_id,
                        alert.mitre_attack_name,
                        incident_id,
                        record_time,
                    ))

        return saved_count, duplicate_count
    finally:
        conn.close()
